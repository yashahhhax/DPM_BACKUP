SELECT
    TO_CHAR(INVENTORY_ITEM_ID) AS INVENTORY_ITEM_ID,
    TO_CHAR(ORGANIZATION_ID) AS ORGANIZATION_ID,
    SEGMENT1,
    DESCRIPTION,
    INVENTORY_ITEM_STATUS_CODE,
    PRIMARY_UNIT_OF_MEASURE,
    TO_CHAR(LIST_PRICE_PER_UNIT) AS LIST_PRICE_PER_UNIT,
    TO_CHAR(UNIT_WEIGHT) AS UNIT_WEIGHT,
    ITEM_TYPE,
    LAST_UPDATE_DATE,
    TO_CHAR(LAST_UPDATED_BY) AS LAST_UPDATED_BY,
    CREATION_DATE,
    TO_CHAR(CREATED_BY) AS CREATED_BY,
    TO_CHAR(LAST_UPDATE_LOGIN) AS LAST_UPDATE_LOGIN
FROM INV.MTL_SYSTEM_ITEMS_B
