SELECT
	SITE,
	CHECK_NUMBER,
	TRANSACTION_ID ,
	PAYMENT_DATE,
	WORKSTATION,
	USER_ID,
	TRANSACTION_TYPE,
	TENDER_TYPE,
	PROFIT_CENTER,
	IIF(CURRENCY='AED', LOCAL_CURRENCY_AMOUNT, TENDER_AMOUNT-TAX_AMOUNT) AS LOCAL_CURRENCY_AMOUNT,
	CURRENCY,
	EXCHANGE_RATE,
	AUTHORIZATION_CODE,
	CREATION_DATE,
	IFACE_STATUS,
	DATA_PROCESSED_TIME,
	TAX_AMOUNT,
	SALE_DATE,
	IIF(TENDER_TYPE in ('Cash', 'US Dollar', 'Euro', 'Saudi Riyal', 'Oman Rial', 'British Paunds', 'Qatari Riyal', 'Kuwait Dinar', 'Bahraini Dinar'), TENDER_AMOUNT, ORIGINAL_AMOUNT) AS ORIGINAL_AMOUNT,
	CHANGE*(-1) as CHANGE ,
	AMOUNT_CURRENCY,
	TENDER_AMOUNT,
	TIP_AMOUNT
FROM dbo.Vw_Export_Payments_ERP
WHERE CHECK_NUMBER <> '20700011'
and CAST(DATA_PROCESSED_TIME AS DATE) >= CAST(DATEADD(DAY, -10, GETDATE()) AS DATE)
