SELECT
    CAST(BOOKING_ID AS DECIMAL(38,18)) AS BOOKING_ID,
    BOOKING_DATE,
    CNX_DATE,
    CAST(CNX_USER AS DECIMAL(38,18)) AS CNX_USER,
    REASON,
    CAST(CNXCOST AS DECIMAL(38,18)) AS CNXCOST,
    CAST(CNXPRICE AS DECIMAL(38,18)) AS CNXPRICE,
    TOTAL_COST,     -- Double left as is
    TOTAL_PRICE,    -- Double left as is
    CAST(RESELL_AMOUNT AS DECIMAL(38,18)) AS RESELL_AMOUNT,
    CNX_NO
FROM TBX.VW_BOOKING_CNX
