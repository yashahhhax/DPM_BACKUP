SELECT
    CAST(BOOKING_ID AS DECIMAL(38,18)) AS BOOKING_ID,
    CAST(CLIENT_ID AS DECIMAL(38,18)) AS CLIENT_ID,
    EXT_CLIENT_REF,
    CUSTOMER_TITLE,
    CUSTOMER_FIRST_NAME,
    CUSTOMER_LAST_NAME,
    coalesce(to_char(cast(CUSTOMER_DATE_OF_BIRTH as date), 'YYYY-MM-DD HH24:MI:SS'), '') as CUSTOMER_DATE_OF_BIRTH,
    BOOKING_STATUS_ID,
    BOOKING_STATUS,
    coalesce(to_char(cast(BOOKING_DATE as date), 'YYYY-MM-DD HH24:MI:SS'), '') as BOOKING_DATE,
	coalesce(to_char(cast(QUOTE_DATE as date), 'YYYY-MM-DD HH24:MI:SS'), '') as QUOTE_DATE,
	coalesce(to_char(cast(DEFINITE_DATE as date), 'YYYY-MM-DD HH24:MI:SS'), '') as DEFINITE_DATE,
    CAST(ADULT AS DECIMAL(38,18)) AS ADULT,
    CAST(CHILD AS DECIMAL(38,18)) AS CHILD,
    CAST(INFANT AS DECIMAL(38,18)) AS INFANT,
    CAST(TOTAL_ADULT_AND_CHILD AS DECIMAL(38,18)) AS TOTAL_ADULT_AND_CHILD,
    CAST(ITEM_COUNT AS DECIMAL(38,18)) AS ITEM_COUNT,
    CAST(LEAD_TIME_DAY AS DECIMAL(38,18)) AS LEAD_TIME_DAY,
    CAST(AMENDED_COUNT AS DECIMAL(38,18)) AS AMENDED_COUNT,
    BOOKING_TYPE,
    CAST(COMMISSION AS DECIMAL(38,18)) AS COMMISSION,
    CAST(PROFIT AS DECIMAL(38,18)) AS PROFIT,
    coalesce(to_char(cast(DEPARTURE_DATE as date), 'YYYY-MM-DD HH24:MI:SS'), '') as DEPARTURE_DATE,
	coalesce(to_char(cast(RETURN_DATE as date), 'YYYY-MM-DD HH24:MI:SS'), '') as RETURN_DATE,
    CAST(TOTAL_PRICE AS DECIMAL(38,18)) AS TOTAL_PRICE,
    CAST(TOTAL_COST AS DECIMAL(38,18)) AS TOTAL_COST,
    CAST(BALANCE_DUE AS DECIMAL(38,18)) AS BALANCE_DUE,
    CAST(BOOKING_CREATED_USER_ID AS DECIMAL(38,18)) AS BOOKING_CREATED_USER_ID,
    BOOKING_CREATED_USER_NAME,
    coalesce(to_char(cast(CREATED_DATE as date), 'YYYY-MM-DD HH24:MI:SS'), '') as CREATED_DATE,
	coalesce(to_char(cast(LAST_CHANGED_TIME as date), 'YYYY-MM-DD HH24:MI:SS'), '') as LAST_CHANGED_TIME,
    COMPANY,
    DIVISION,
    OPTION_STATUS,
    CAST(DISCOUNT AS DECIMAL(38,18)) AS DISCOUNT,
    MEDIA_CODE,
    CHANNEL,
    CURRENCY,
    CAST(SELLING_TO_BASE_EXCHANGE_RATE AS DECIMAL(38,18)) AS SELLING_TO_BASE_EXCHANGE_RATE,
    CAST(TRAVEL_AGENT AS DECIMAL(38,18)) AS TRAVEL_AGENT,
    CLIENT_NAME,
    CLIENT_TYPE,
    CLIENT_GROUP,
    CNX_REASON_ID,
    coalesce(to_char(cast(QUOTE_EXPIRY_DATE as date), 'YYYY-MM-DD HH24:MI:SS'), '') as QUOTE_EXPIRY_DATE,
	coalesce(to_char(cast(CNX_DATE as date), 'YYYY-MM-DD HH24:MI:SS'), '') as CNX_DATE,
    PROMOTION_CODE,
    CAST(ERRATA_FLAG AS DECIMAL(38,18)) AS ERRATA_FLAG,
    BRAND,
    coalesce(to_char(cast(FIRM_DATE as date), 'YYYY-MM-DD HH24:MI:SS'), '') as FIRM_DATE,
    FLOW,
    SUPP_REF_NUMBER,
    CAST(RESELL_AMOUNT AS DECIMAL(38,18)) AS RESELL_AMOUNT
FROM TBX.VW_BOOKING
