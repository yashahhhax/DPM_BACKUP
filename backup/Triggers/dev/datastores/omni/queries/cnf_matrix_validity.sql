SELECT
cast(CP.PERFDATETIME as date) as report_date,
MC.MATRIXCELLAK as product_id,
Sum(EC.QUANTITY) AS total_qty,
( Sum(EC.QUANTITY) - Sum(EC.INUSEQUANTITY) - Sum(EC.BOOKEDQUANTITY) - Sum(EC.PAIDQUANTITY) ) AS available_qty
FROM   dbo.CNF_MATRIXCELL MC
INNER JOIN
(
   SELECT
   MCE.MATRIXCELLID,
   Cast(PV.VALIDITYXML AS XML).value('(/ROOT/VALIDITYLIST//VALIDITYLIST//EVENTID)[1]', 'float') AS Eventid
   FROM dbo.CNF_MATRIXCELL MCE WITH(NOLOCK)
    CROSS APPLY (SELECT ATTRIBUTEID
    			  FROM   dbo.CNF_ATTRIBUTESETDETAIL WITH(NOLOCK)
    			  WHERE  ATTRIBUTESETID = MCE.ATTRIBUTESETID) ASD
    CROSS APPLY (SELECT VALIDITYXML
    			  FROM   dbo.CNF_PRODUCTVALIDITY WITH(NOLOCK)
    			  WHERE  REFERENCETABLE = 105
    			  AND REFERENCEID = ASD.ATTRIBUTEID) PV
   WHERE
   Cast(PV.VALIDITYXML AS XML).value('(/ROOT/VALIDITYLIST//VALIDITYLIST//EVENTID)[1]', 'float') IS NOT NULL
) EVE
        ON EVE.MATRIXCELLID = MC.MATRIXCELLID
INNER JOIN dbo.CNF_PERFORMANCE CP
        ON CP.EVENTID = EVE.EVENTID
INNER JOIN dbo.CNF_SPACESTRUCTURE SS
        ON SS.PERFORMANCEID = CP.PERFORMANCEID
INNER JOIN dbo.CNF_ENVELOPECAPACITY EC
        ON EC.SPACESTRUCTUREID = SS.SPACESTRUCTUREID
WHERE 1=1
        --AND  MC.MATRIXCELLAK IN (SELECT VALUE FROM   STRING_SPLIT('SWA.EVN1.MCC145,SWA.EVN1.MCC150,SWA.EVN1.MCC144,SWA.EVN1.MCC148,SWA.EVN1.MCC146,SWA.EVN1.MCC141,SWA.EVN1.MCC149,SWA.EVN1.MCC142,SWA.EVN1.MCC143,SWA.EVN1.MCC147,SWA.EVN1.MCC679,SWA.EVN1.MCC223,SWA.EVN1.MCC229,SWA.EVN1.MCC572,SWA.EVN1.MCC230,SWA.EVN1.MCC474,SWA.EVN1.MCC681,SWA.EVN24.MCC1',','))
       AND CP.PERFDATETIME  >= '2025-01-01'
       AND CP.PERFDATETIME < DATEADD(DAY, 30, CAST(GETDATE() AS DATE))
GROUP  BY MC.MATRIXCELLAK ,cast(CP.PERFDATETIME as date)
order by MC.MATRIXCELLAK ,cast(CP.PERFDATETIME as date)
